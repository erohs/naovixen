/** The space tokens a layout can use as its gap, named after `--space-<value>`. */
export enum Space {
    BetweenText = 'between-text',
    BetweenContent = 'between-content',
    BetweenBlocks = 'between-blocks',
    BetweenGroups = 'between-groups',
    BetweenRegions = 'between-regions',
    BetweenSections = 'between-sections',
}
